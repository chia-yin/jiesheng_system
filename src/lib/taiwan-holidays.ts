export function getTaiwanHolidayName(dateKey: string): string | undefined {
  return BY_DATE[dateKey];
}

export function isTaiwanHoliday(dateKey: string): boolean {
  return Boolean(BY_DATE[dateKey]);
}

export function listTaiwanHolidays(year?: number): TaiwanHoliday[] {
  return Object.entries(BY_DATE)
    .filter(([date]) => (year == null ? true : date.startsWith(String(year))))
    .map(([date, name]) => ({ date, name }))
    .sort((a, b) => a.date.localeCompare(b.date));
}
